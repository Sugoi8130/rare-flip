export function pixelText(ctx: CanvasRenderingContext2D, text: string, cx: number, cy: number, maxWidth: number, color: string) {
  const chars = [...text.toUpperCase()];
  const size = Math.max(1, Math.min(5, Math.floor(maxWidth / Math.max(1, chars.length * 6 - 1))));
  const left = Math.round(cx - (chars.length * 6 - 1) * size / 2), top = Math.round(cy - 7 * size / 2);
  const raster = document.createElement("canvas"); raster.width = Math.max(1, chars.length * 6 - 1); raster.height = 7;
  const art = raster.getContext("2d")!; art.fillStyle = color;
  chars.forEach((char, i) => letters[char]?.split("/").forEach((row, y) => [...row].forEach((bit, x) => {
    if (bit === "1") art.fillRect(i * 6 + x, y, 1, 1);
  })));
  ctx.imageSmoothingEnabled = false;
  ctx.drawImage(raster, left, top, raster.width * size, 7 * size);
}
