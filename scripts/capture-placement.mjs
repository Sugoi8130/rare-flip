import assert from "node:assert/strict";
import { chromium } from "playwright";
import { resolve } from "node:path";
import { installFixture, createArtworkFixture } from "../node_modules/@rarefriends/friendsdk/scripts/browser-fixture.mjs";

const browser = await chromium.launch({ headless:true });
try {
  const page = await browser.newPage({ viewport:{ width:1280,height:800 }, hasTouch:true });
  const errors = []; page.on("pageerror", error => errors.push(error.message));
  await installFixture(page, "http://127.0.0.1:4173", { artworkCall:await createArtworkFixture() });
  await page.goto("http://127.0.0.1:4173");
  await page.getByRole("button", { name:/^Connect (wallet|Browser wallet)$/ }).click();
  await page.getByRole("button", { name:/^Friend #7730\b/ }).click();
  const game = page.frameLocator("iframe"), scene = game.locator(".scene");
  const picker = game.getByRole("dialog", { name:"Choose decoration position" });
  await game.getByRole("button", { name:"SHOP",exact:true }).click();
  await game.getByRole("button", { name:"Preview JELLY AQUARIUM" }).click();
  await game.getByRole("button", { name:"BUY · 15 FLIP",exact:true }).click();
  await game.getByRole("button", { name:"EQUIP",exact:true }).click();
  await picker.waitFor();
  assert.equal(await picker.locator(".placement-spot").count(),6);
  assert.equal(await game.getByRole("button", { name:"PLACE HERE",exact:true }).isDisabled(),true);
  const canvas = scene.locator("canvas"), initialX = await canvas.getAttribute("data-player-x");
  await page.keyboard.down("d"); await page.waitForTimeout(100); await page.keyboard.up("d");
  assert.equal(await canvas.getAttribute("data-player-x"),initialX,"Placement pauses movement");
  await game.getByRole("button", { name:"Place at LEFT AISLE",exact:true }).click();
  assert.deepEqual(JSON.parse(await scene.getAttribute("data-room-positions")).aquarium,{ x:235,y:265 });
  assert.equal(await scene.getAttribute("data-decorations"),"","Preview must not equip before confirmation");
  await page.waitForTimeout(150);
  await page.locator(".rf-game-frame").screenshot({ path:resolve("outputs/rare-flip-placement-desktop.png") });
  await game.getByRole("button", { name:"CANCEL",exact:true }).click();
  assert.deepEqual(JSON.parse(await scene.getAttribute("data-room-positions")),{});
  assert.equal(await game.getByRole("button", { name:"BUY · 15 FLIP",exact:true }).count(),0,"Cancellation preserves ownership");
  await game.getByRole("button", { name:"EQUIP",exact:true }).click();
  await game.getByRole("button", { name:"Place at LEFT AISLE",exact:true }).click();
  await game.getByRole("button", { name:"PLACE HERE",exact:true }).click();
  assert.equal(await scene.getAttribute("data-decorations"),"aquarium");
  await game.getByRole("button", { name:"SHOP",exact:true }).click();
  await game.getByRole("button", { name:"Preview LUCKY CLOUD CAT" }).click();
  await game.getByRole("button", { name:"BUY · 45 FLIP",exact:true }).click();
  await game.getByRole("button", { name:"EQUIP",exact:true }).click();
  assert.equal(await game.getByRole("button", { name:"Place at LEFT AISLE",exact:true }).isDisabled(),true,"Occupied preset must be blocked");
  await page.setViewportSize({ width:390,height:844 });
  await game.getByRole("button", { name:"Place at RIGHT CORNER",exact:true }).tap();
  await page.waitForTimeout(150);
  await page.locator(".rf-game-frame").screenshot({ path:resolve("outputs/rare-flip-placement-mobile.png") });
  await game.getByRole("button", { name:"PLACE HERE",exact:true }).tap();
  assert.deepEqual(JSON.parse(await scene.getAttribute("data-room-positions")),{ aquarium:{ x:235,y:265 },cat:{ x:725,y:365 } });
  assert.equal(await scene.getAttribute("data-decorations"),"aquarium,cat");
  await game.getByRole("button", { name:"SHOP",exact:true }).tap();
  await game.getByRole("button", { name:"Preview LUCKY CLOUD CAT" }).tap();
  await game.getByRole("button", { name:"UNEQUIP",exact:true }).tap();
  await game.getByRole("button", { name:"EQUIP",exact:true }).tap();
  await game.getByRole("button", { name:"Place at FRONT RIGHT",exact:true }).tap();
  await page.keyboard.press("Escape");
  assert.equal(await scene.getAttribute("data-decorations"),"aquarium");
  assert.deepEqual(JSON.parse(await scene.getAttribute("data-room-positions")).cat,{ x:725,y:365 },"Cancel preserves previous saved position");
  assert.deepEqual(errors,[]);
  console.log("PASS: EQUIP opens six presets, live preview, confirm, occupied guard, pause, cancellation, saved positions and touch.");
} finally { await browser.close(); }
