import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { installFixture,createArtworkFixture } from '../node_modules/@rarefriends/friendsdk/scripts/browser-fixture.mjs';
import { resolve } from 'node:path';
const origin='http://127.0.0.1:4173', errors=[];
const browser=await chromium.launch({headless:true});
try {
  const page=await browser.newPage({viewport:{width:1280,height:800},hasTouch:true,reducedMotion:'reduce'});
  page.on('pageerror',e=>errors.push(e.message));
  await installFixture(page,origin,{artworkCall:await createArtworkFixture()});
  await page.goto(origin);
  await page.getByRole('button',{name:/^Connect (wallet|Browser wallet)$/}).click();
  await page.getByRole('button',{name:/^Friend #7730\b/}).click();
  await page.frameLocator("iframe").getByRole("button",{ name:"ENTER ROOM →",exact:true }).click();
  const game=page.frameLocator('iframe'),scene=game.locator('.scene'),canvas=game.locator('.scene canvas');
  await game.getByRole('button',{name:'SHOP',exact:true}).click();
  await game.getByRole('button',{name:'PET',exact:true}).click();
  assert.equal(await game.locator('.shop-item').count(),4);
  await game.getByRole('button',{name:'Preview STAR DRAGON'}).click();
  assert(await game.getByRole('button',{name:'BUY · 300 FLIP',exact:true}).isDisabled());
  await game.getByRole('button',{name:'DEMO +500 FLIP',exact:true}).click();
  await game.getByRole('button',{name:'DEMO +500 FLIP',exact:true}).click();
  await game.locator('.shop-item canvas[data-loaded="true"]').first().waitFor();
  await page.waitForTimeout(300);
  await page.locator('.rf-game-frame').screenshot({path:resolve('outputs/rare-flip-pet-shop.png')});
  const base=await canvas.screenshot();
  for (const [name,id,price,costume] of [['MINT SLIME','mint-slime',105,35],['CLOUD FOX','cloud-fox',180,60],['MOON BAT','moon-bat',225,75],['STAR DRAGON','star-dragon',300,100]]) {
    assert.equal(price,3*costume);
    await game.getByRole('button',{name:`Preview ${name}`}).click();
    await game.getByRole('button',{name:`BUY · ${price} FLIP`,exact:true}).click();
    await game.getByRole('button',{name:'EQUIP',exact:true}).click();
    await game.getByRole('button',{name:'Close shop'}).click();
    await page.waitForTimeout(300);
    assert.equal(await canvas.getAttribute('data-pet'),id);
    assert(!(await canvas.screenshot()).equals(base),'Pet must draw on playable canvas');
    await page.locator('.rf-game-frame').screenshot({path:resolve(`outputs/rare-flip-${id}-live.png`)});
    await game.getByRole('button',{name:'SHOP',exact:true}).click();
    await game.getByRole('button',{name:'PET',exact:true}).click();
  }
  await game.getByRole('button',{name:'Close shop'}).click();
  const before=Number(await canvas.getAttribute('data-pet-x'));
  await page.keyboard.down('d'); await page.waitForTimeout(650); await page.keyboard.up('d');
  await page.waitForTimeout(200);
  assert(Number(await canvas.getAttribute('data-pet-x'))>before+15,'Pet follows real movement');
  assert.equal(await canvas.getAttribute('data-pet-facing'),'right');
  await page.keyboard.down('a'); await page.waitForTimeout(350); await page.keyboard.up('a');
  assert.equal(await canvas.getAttribute('data-pet-facing'),'left');
  await game.getByRole('button',{name:'SHOP',exact:true}).click();
  const frozen=await canvas.getAttribute('data-pet-x'); await page.waitForTimeout(200);
  assert.equal(await canvas.getAttribute('data-pet-x'),frozen,'Shop pauses pet movement');
  await game.getByRole('button',{name:'ROOM',exact:true}).click();
  assert.equal(await game.locator('.shop-item').count(),6);
  for (const [name,price,spot] of [['GOLD TROPHY',60,'FRONT LEFT'],['FRIEND STATUE',75,'RIGHT AISLE'],['RETRO RADIO',45,'LEFT AISLE']]) {
    await game.getByRole('button',{name:`Preview ${name}`}).click();
    await game.getByRole('button',{name:`BUY · ${price} FLIP`,exact:true}).click();
    await game.getByRole('button',{name:'EQUIP',exact:true}).click();
    await game.getByRole('button',{name:`Place at ${spot}`,exact:true}).click();
    await game.getByRole('button',{name:'PLACE HERE',exact:true}).click();
    await game.getByRole('button',{name:'SHOP',exact:true}).click();
  }
  await page.locator('.rf-game-frame').screenshot({path:resolve('outputs/rare-flip-new-room-shop.png')});
  await game.getByRole('button',{name:'Close shop'}).click();
  const room=JSON.parse(await scene.getAttribute('data-room-positions'));
  assert.deepEqual(Object.keys(room).sort(),['radio','statue','trophy']);
  await page.waitForTimeout(300);
  await page.locator('.rf-game-frame').screenshot({path:resolve('outputs/rare-flip-pets-decor-live.png')});
  await game.getByRole('button',{name:'SHOP',exact:true}).click();
  await game.getByRole('button',{name:'PET',exact:true}).click();
  await game.getByRole('button',{name:'Preview STAR DRAGON'}).click();
  await game.getByRole('button',{name:'UNEQUIP',exact:true}).click();
  await game.getByRole('button',{name:'Close shop'}).click();
  assert.equal(await canvas.getAttribute('data-pet'),'');
  await page.setViewportSize({width:390,height:844});
  await game.getByRole('button',{name:'SHOP',exact:true}).tap();
  await game.getByRole('button',{name:'PET',exact:true}).tap();
  await game.getByRole('button',{name:'Preview CLOUD FOX'}).tap();
  await game.getByRole('button',{name:'EQUIP',exact:true}).tap();
  const overflow=await game.locator('.flip-shop').evaluate(el=>el.scrollWidth>el.clientWidth+2);
  assert.equal(overflow,false,'Shop fits mobile width');
  await page.locator('.rf-game-frame').screenshot({path:resolve('outputs/rare-flip-pet-shop-mobile.png')});
  await game.getByRole('button',{name:'Close shop'}).tap();
  assert.equal(await canvas.getAttribute('data-pet'),'cloud-fox');
  assert.deepEqual(errors,[]);
  console.log('PASS: 4 PET prices, buy/equip/unequip, actual canvas rendering, following/turning/pause, 3 decorations placement and mobile touch.');
} finally { await browser.close(); }
